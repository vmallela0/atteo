// Built CSS/JS (and fonts) written to dist/web at `npm run build:assets` and served as Workers static assets
// (wrangler.jsonc assets.directory). Pages still ask for /app.css?v=<hash> etc.; the query string busts caches.
// Matching GETs do not run the Worker (run_worker_first lists only mermaid.min.js). This module is the fallback for
// Worker-to-Worker fetches (the landing Worker) which invoke the script and skip the assets pipeline.

import { CODE_COLOR_PATH, CODE_COLOR_SCRIPT } from "./codecolor";
import { BOARD_JS, BOARD_JS_PATH } from "./html";
import { HOST_PAGE_JS } from "./hostUi";
import { PALETTE_CSS, PALETTE_JS } from "./palette";
import {
  APP_CSS,
  APP_JS,
  BOARD_PREFETCH_PATH,
  BOARD_PREFETCH_RULES,
  BUG_PAGE_JS,
  FEEDBACK_PAGE_JS,
  PAGE_CSS,
  SHELL_PAGE_JS,
} from "./ui";

const IMMUTABLE = "public, max-age=31536000, immutable";
const CSS = "text/css; charset=utf-8";
const JS = "text/javascript; charset=utf-8";

export interface BuiltTextAsset {
  path: string;
  body: string;
  contentType: string;
  cacheControl: string;
}

/** The files `scripts/build-web-assets.mjs` writes into dist/web (plus copied fonts and mermaid.min.js). */
export function builtTextAssets(): BuiltTextAsset[] {
  return [
    { path: "/app.css", body: APP_CSS, contentType: CSS, cacheControl: IMMUTABLE },
    { path: "/app.js", body: APP_JS, contentType: JS, cacheControl: IMMUTABLE },
    { path: BOARD_JS_PATH, body: BOARD_JS, contentType: JS, cacheControl: IMMUTABLE },
    { path: "/shell.js", body: SHELL_PAGE_JS, contentType: JS, cacheControl: IMMUTABLE },
    { path: "/bug.js", body: BUG_PAGE_JS, contentType: JS, cacheControl: IMMUTABLE },
    { path: "/feedback.js", body: FEEDBACK_PAGE_JS, contentType: JS, cacheControl: IMMUTABLE },
    { path: "/host.js", body: HOST_PAGE_JS, contentType: JS, cacheControl: IMMUTABLE },
    { path: "/palette.js", body: PALETTE_JS, contentType: JS, cacheControl: IMMUTABLE },
    { path: "/palette.css", body: PALETTE_CSS, contentType: CSS, cacheControl: IMMUTABLE },
    { path: CODE_COLOR_PATH, body: CODE_COLOR_SCRIPT, contentType: JS, cacheControl: IMMUTABLE },
    { path: BOARD_PREFETCH_PATH, body: BOARD_PREFETCH_RULES, contentType: "application/speculationrules+json", cacheControl: "public, max-age=3600" },
    ...Object.entries(PAGE_CSS).map(([path, body]) => ({ path, body, contentType: CSS, cacheControl: IMMUTABLE })),
  ];
}

const TEXT_PATHS = new Set(builtTextAssets().map((a) => a.path));

/** /fonts/<file>.woff2 — unknown names 404 from the assets pipeline (or this fallback). */
export function isFontAssetPath(path: string): boolean {
  if (!path.startsWith("/fonts/")) return false;
  const name = path.slice("/fonts/".length);
  return /^[a-z0-9][a-z0-9._-]*\.woff2$/i.test(name);
}

export function isBuiltAssetPath(path: string): boolean {
  return TEXT_PATHS.has(path) || isFontAssetPath(path);
}

/** _headers for dist/web: long cache (pages always send ?v=), nosniff, CORS on fonts (landing preload). */
export function staticAssetHeadersFile(): string {
  const lines = ["# Generated by scripts/build-web-assets.mjs. Applied only to static asset responses, not Worker routes."];
  for (const a of builtTextAssets()) {
    lines.push("", a.path, `  Content-Type: ${a.contentType}`, `  Cache-Control: ${a.cacheControl}`, "  X-Content-Type-Options: nosniff");
  }
  lines.push(
    "",
    "/fonts/*",
    "  Content-Type: font/woff2",
    `  Cache-Control: ${IMMUTABLE}`,
    "  Access-Control-Allow-Origin: *",
    "  X-Content-Type-Options: nosniff",
    "",
  );
  return lines.join("\n");
}

/** GET/HEAD of a built file via the ASSETS binding. Null if this isn't one of those paths. */
export async function serveBuiltAsset(env: { ASSETS?: Fetcher }, request: Request, path: string): Promise<Response | null> {
  if (request.method !== "GET" && request.method !== "HEAD") return null;
  if (!isBuiltAssetPath(path)) return null;
  if (!env.ASSETS) return new Response("not found", { status: 404 });
  return env.ASSETS.fetch(new Request(new URL(path, request.url), { method: request.method }));
}
