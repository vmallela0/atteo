import { SHOTS_DIR } from "./lib/shots.mjs";
import { chromium } from "playwright-core";
const BASE=process.env.BASE||"http://localhost:8787";
const ops = async (p, b) => (await fetch(`${BASE}/api/ops/${p}`, { method: "POST", headers: { "x-admin-key": "ci-admin-key", "content-type": "application/json" }, body: JSON.stringify(b) })).json();
const run=Date.now().toString(36).slice(-4), A=`own${run}`, V=`view${run}`, F=`frd${run}`;
for (const u of [A,V,F]) await ops("users",{name:u,email:`${u}@example.com`,verified:"true"});
const board=(await ops("boards",{user:A,title:`Access ${run}`})).board.id; await ops("members",{board,user:V});
const ck={};for(const u of [A,V,F])ck[u]=(await ops("sessions",{user:u})).cookie;
const api=(u,path,body)=>fetch(`${BASE}${path}`,{method:body?"POST":"GET",headers:{"content-type":"application/json",cookie:ck[u]},body:body?JSON.stringify(body):undefined});
await api(A,"/api/friends/request",{user:F});await api(F,`/api/friends/${A}/accept`,{});
let fails=0;const check=(ok,m)=>{console.log(`${ok?"✓":"✗"} ${m}`);if(!ok)fails++};
const b = await chromium.launch({ executablePath: process.env.PW_CHROME || undefined });
const page=async(u)=>{const ctx=await b.newContext({viewport:{width:1280,height:820}});const [k,...v]=ck[u].split(";")[0].split("=");await ctx.addCookies([{name:k,value:v.join("="),url:BASE}]);const p=await ctx.newPage();p.errors=[];p.on("pageerror",e=>p.errors.push(e.message));return p};
const p=await page(A);
await p.goto(`${BASE}/b/${board}`);await p.waitForTimeout(600);
await p.locator('[data-open="invite"]').first().click();await p.waitForTimeout(800);
check(await p.locator("#invite").isVisible(),"Invite opens Members & access");
check(await p.locator(`#acc-members [data-user="${V}"]`).count()===1,"members list shows the other member");
await p.locator(`#acc-members [data-user="${V}"] [data-acc="role"]`).selectOption("viewer");await p.waitForTimeout(800);
const r=await (await api(A,`/api/boards/${board}/members`)).json();
check(r.members?.find(m=>m.user===V)?.role==="viewer","changing the role saves it");
await p.locator("#link-make").click();await p.waitForTimeout(700);
check((await p.locator("#link-url").inputValue().catch(()=>"")).startsWith("http"),"Create link shows a copyable link");
check(await p.locator("#acc-links .acc-row").count()===1,"…and lists it with Revoke");
await p.locator("#acc-audit").evaluate(e=>e.closest("details").open=true);
check((await p.locator("#acc-audit").innerText()).includes("changed access for"),"Activity lists the role change");
await p.locator("#inv-email").fill(F.slice(0,4));await p.waitForTimeout(600);
check(await p.locator(`#inv-sug [data-friend-pick="${F}"]`).isVisible(),"typing suggests a friend who isn't here yet");
check(await p.locator(`#inv-sug [data-friend-pick="${V}"]`).count()===0,"…and not someone already on the board");
await p.locator("#inv-email").press("Enter");check((await p.locator("#inv-email").inputValue())===F,"Enter picks the friend");
await p.locator(".acc-inv .btn.primary").click();await p.waitForTimeout(800);
const res=await p.locator(".acc-inv [data-result]").innerText();
check(res.includes(F)&&!res.includes("@example.com"),`inviting by name works and never shows their email ("${res.slice(0,70)}")`);
await p.reload();await p.waitForTimeout(500);await p.locator('[data-open="invite"]').first().click();await p.waitForTimeout(500);
const pend=await p.locator("#invite").innerText();check(pend.includes(F)&&!pend.includes(`${F}@example.com`),"pending invites show the friend by name");
const box=await p.locator("#invite").boundingBox();check(box.width<=720&&box.height<=820,`dialog fits (${Math.round(box.width)}×${Math.round(box.height)})`);
await p.screenshot({path:`${SHOTS_DIR}/access.png`});
check(await p.locator('#board-info [data-open="delete-board"]').count()===0,"Board info has no Archive/Delete (they live in this dialog)");
await p.locator('#invite [data-open="delete-board"]').click();await p.waitForTimeout(300);
check(await p.locator("#delete-board").isVisible()&&!(await p.locator("#invite").isVisible()),"Delete board… replaces this dialog with the confirmation");
await p.keyboard.press("Escape");await p.waitForTimeout(200);
check(p.errors.length===0,`no owner page errors ${p.errors.join(" | ")}`);
const q=await page(V);
await q.goto(`${BASE}/b/${board}`);await q.waitForTimeout(600);
check(!(await q.locator(".composer").isVisible()),"a viewer has no composer");
check((await q.locator(".topbar, header").first().innerText()).includes("View only")||(await q.locator("body").innerText()).includes("View only"),"…and sees View only");
check(!(await q.locator('.actions [data-open="invite"], .actions [data-open="invite"]').first().isVisible().catch(()=>false)),"…and no Invite button");
const w=await api(V,`/api/boards/${board}/entries`,{type:"note",text:"hi"});check(w.status===403,`a viewer's write is refused (${w.status})`);
await q.screenshot({path:`${SHOTS_DIR}/viewer.png`});
check(q.errors.length===0,`no viewer page errors ${q.errors.join(" | ")}`);
await b.close();console.log(fails?`${fails} FAILED`:"all access checks passed");
