// Message numbers stay out of people's way: header #N only on hover; "#N" in text and in "reply to" lines are titled chips.
import { SHOTS_DIR } from "./lib/shots.mjs";
import { chromium } from "playwright-core";
const BASE=process.env.BASE||"http://localhost:8787";
const ops = async (p, b) => (await fetch(`${BASE}/api/ops/${p}`, { method: "POST", headers: { "x-admin-key": "ci-admin-key", "content-type": "application/json" }, body: JSON.stringify(b) })).json();
const run=Date.now().toString(36).slice(-4), A=`nr${run}`;
await ops("users",{name:A,email:`${A}@example.com`,verified:"true"});
const tok=(await ops("tokens",{user:A})).token;
const board=(await ops("boards",{user:A,title:`Numbers ${run}`})).board.id;
const call=async(name,args)=>(await (await fetch(`${BASE}/mcp?board=${board}`,{method:"POST",headers:{"content-type":"application/json",authorization:`Bearer ${tok}`},body:JSON.stringify({jsonrpc:"2.0",id:1,method:"tools/call",params:{name,arguments:args}})})).json()).result.content[0].text;
await call("read",{});
const first=+(await call("post",{type:"decision",title:"Ship on Friday",text:"We ship on Friday.",reply_to:0})).match(/#(\d+)/)[1];
await call("post",{type:"note",text:`Following up on #${first}: all set. Code like \`#${first}\` stays as is.`,reply_to:0});
await call("post",{type:"note",text:"Agreed.",reply_to:first});
const ck=(await ops("sessions",{user:A})).cookie;
let fails=0;const check=(ok,m)=>{console.log(`${ok?"✓":"✗"} ${m}`);if(!ok)fails++};
const b=await chromium.launch({executablePath: process.env.PW_CHROME || undefined});
const ctx=await b.newContext({viewport:{width:1280,height:800}});const [k,...v]=ck.split(";")[0].split("=");await ctx.addCookies([{name:k,value:v.join("="),url:BASE}]);
const p=await ctx.newPage();const errors=[];p.on("pageerror",e=>errors.push(e.message));
await p.goto(`${BASE}/b/${board}`);await p.waitForTimeout(1000);
const seqOp=await p.evaluate(s=>getComputedStyle(document.querySelector('#e'+s+' .meta .seq')).opacity,first);
check(seqOp==="0","the header's #N is hidden until hover");
await p.locator(`#e${first}`).hover();await p.waitForTimeout(250);
check(await p.evaluate(s=>getComputedStyle(document.querySelector('#e'+s+' .meta .seq')).opacity,first)==="1","…and shows on hover");
const chip=await p.evaluate(()=>[...document.querySelectorAll('#thread .body a.ref')].map(a=>a.textContent));
check(chip.length===1&&chip[0]==="↗ Ship on Friday",`"#${first}" in text reads as a chip with the title: ${JSON.stringify(chip)}`);
check(await p.evaluate(()=>!![...document.querySelectorAll('#thread .body code')].find(c=>/#\d+/.test(c.textContent))),"…but not inside code");
await p.locator('#thread .body a.ref').first().click();await p.waitForTimeout(500);
check(/#e\d+$/.test(p.url()),"clicking the chip goes to that message");
check(await p.evaluate(()=>![...document.querySelectorAll('#board-info .sum li .n')].some(n=>n.offsetParent)),"the sidebar lists show no numbers");
await p.locator(`#e${first}`).screenshot({path:`${SHOTS_DIR}/numrefs.png`}).catch(()=>{});
check(errors.length===0,`no page errors ${errors.join(" | ")}`);
await b.close();console.log(fails?`${fails} FAILED`:"all number checks passed");
