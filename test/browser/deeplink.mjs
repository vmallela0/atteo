import { chromium } from "playwright-core";
const BASE=process.env.BASE||"http://localhost:8787";
const ops = async (p, b) => (await fetch(`${BASE}/api/ops/${p}`, { method: "POST", headers: { "x-admin-key": "ci-admin-key", "content-type": "application/json" }, body: JSON.stringify(b) })).json();
const run=Date.now().toString(36).slice(-4), A=`dl${run}`;
await ops("users",{name:A,email:`${A}@example.com`,verified:"true"});
const tok=(await ops("tokens",{user:A})).token;
const board=(await ops("boards",{user:A,title:`Deep ${run}`})).board.id;
const call=async(name,args)=>(await (await fetch(`${BASE}/mcp?board=${board}`,{method:"POST",headers:{"content-type":"application/json",authorization:`Bearer ${tok}`},body:JSON.stringify({jsonrpc:"2.0",id:1,method:"tools/call",params:{name,arguments:args}})})).json()).result.content[0].text;
await call("read",{});
await call("post",{type:"decision",title:"Early decision",text:"decided early",reply_to:0});
for(let i=0;i<40;i++) await call("post",{type:"note",text:`filler ${i}\n`.repeat(3),reply_to:0});
const ck=(await ops("sessions",{user:A})).cookie;
let fails=0;const check=(ok,m)=>{console.log(`${ok?"✓":"✗"} ${m}`);if(!ok)fails++};
const b=await chromium.launch({executablePath: process.env.PW_CHROME || undefined});
const ctx=await b.newContext({viewport:{width:1280,height:800}});const [k,...v]=ck.split(";")[0].split("=");await ctx.addCookies([{name:k,value:v.join("="),url:BASE}]);
const p=await ctx.newPage();await p.goto(`${BASE}/b/${board}`);await p.waitForTimeout(1000);
const vis=async()=>{const r=await p.locator("#e1").boundingBox();return r&&r.y>0&&r.y<800};
await p.locator('#board-info a[href="#e1"]').first().click();await p.waitForTimeout(1500);
check(await vis(),"clicking the sidebar link to #1 shows #1 (and it stays there)");
const p2=await ctx.newPage();await p2.goto(`${BASE}/b/${board}#e1`);await p2.waitForTimeout(1500);
const r2=await p2.locator("#e1").boundingBox();check(r2&&r2.y>0&&r2.y<800,"opening the page at #e1 lands on #1");
await b.close();console.log(fails?`${fails} FAILED`:"all deep-link checks passed");
