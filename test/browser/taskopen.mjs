import { SHOTS_DIR } from "./lib/shots.mjs";
import { chromium } from "playwright-core";
const BASE=process.env.BASE||"http://localhost:8787";
const ops = async (p, b) => (await fetch(`${BASE}/api/ops/${p}`, { method: "POST", headers: { "x-admin-key": "ci-admin-key", "content-type": "application/json" }, body: JSON.stringify(b) })).json();
const run=Date.now().toString(36).slice(-4), A=`to${run}`;
await ops("users",{name:A,email:`${A}@example.com`,verified:"true"});
const tok=(await ops("tokens",{user:A})).token;
const board=(await ops("boards",{user:A,title:`Tasks ${run}`})).board.id;
const call=async(name,args)=>(await (await fetch(`${BASE}/mcp?board=${board}`,{method:"POST",headers:{"content-type":"application/json",authorization:`Bearer ${tok}`},body:JSON.stringify({jsonrpc:"2.0",id:1,method:"tools/call",params:{name,arguments:args}})})).json()).result.content[0].text;
await call("read",{});
console.log((await call("task",{action:"create",title:"On-it to done marker, no Unverified on claims, agent names on reactions (jxn #254 #256 #257)",body:"- [x] one\n- [ ] two\n\nlong body ".repeat(20)})).slice(0,60));
const ck=(await ops("sessions",{user:A})).cookie;
let fails=0;const check=(ok,m)=>{console.log(`${ok?"✓":"✗"} ${m}`);if(!ok)fails++};
const b=await chromium.launch({executablePath: process.env.PW_CHROME || undefined});
const ctx=await b.newContext({viewport:{width:1280,height:800}});const [k,...v]=ck.split(";")[0].split("=");await ctx.addCookies([{name:k,value:v.join("="),url:BASE}]);
const p=await ctx.newPage();const errors=[];p.on("pageerror",e=>errors.push(e.message));p.on("console",m=>{if(m.type()==="error")errors.push(m.text()+" "+JSON.stringify(m.location()))});p.on("requestfailed",r=>errors.push("reqfail "+r.url()));p.on("response",r=>{if(r.status()>=400)errors.push(r.status()+" "+r.url())});
await p.goto(`${BASE}/b/${board}`);await p.waitForTimeout(1200);
const btn=p.locator('[data-tk="open"]').first();
check(await btn.count()===1,"task strip has Open");
const t0=Date.now();
await btn.click({timeout:5000}).catch(e=>errors.push("click: "+e.message));
await p.waitForTimeout(800);
const alive=await Promise.race([p.evaluate(()=>1),new Promise(r=>setTimeout(()=>r(0),3000))]);
check(alive===1,"page still responds after Open ("+(Date.now()-t0)+"ms)");
const st=await p.evaluate(()=>{const d=document.getElementById('task-dlg');const r=d.getBoundingClientRect();const cs=getComputedStyle(d);return {open:d.open,x:r.x,y:r.y,w:r.width,h:r.height,vis:cs.visibility,disp:cs.display,op:cs.opacity}}).catch(e=>"ERR "+e.message);
check(st.open&&st.w>100&&st.h>100&&st.op==="1","Open from the conversation shows the task dialog ("+JSON.stringify(st)+")");
check((await p.inputValue("#td-title")).startsWith("On-it to done"),"it's the task that was opened");
await p.keyboard.press("Escape");await p.waitForTimeout(300);
check(!(await p.evaluate(()=>document.getElementById('task-dlg').open)),"Escape closes it");
await p.locator("#composer-text").click();await p.keyboard.type("still works");
check((await p.inputValue("#composer-text"))==="still works","the page takes input again");
await p.screenshot({path:`${SHOTS_DIR}/taskopen.png`});
const real=errors.filter(e=>!e.includes("/avatar/")&&!e.includes("/typing")); // a typing ping cut off by the page closing is fine
check(real.length===0,"no errors "+real.join(" | "));
await b.close();console.log(fails?`${fails} FAILED`:"all task-open checks passed");
