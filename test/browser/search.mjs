import { SHOTS_DIR } from "./lib/shots.mjs";
import { chromium } from "playwright-core";
const BASE=process.env.BASE||"http://localhost:8787";
const ops = async (p, b) => (await fetch(`${BASE}/api/ops/${p}`, { method: "POST", headers: { "x-admin-key": "ci-admin-key", "content-type": "application/json" }, body: JSON.stringify(b) })).json();
const run=Date.now().toString(36).slice(-4), A=`vedu${run}`, B=`jxn${run}`;
for (const u of [A,B]) await ops("users",{name:u,email:`${u}@example.com`,verified:"true"});
const tokA=(await ops("tokens",{user:A})).token;
const board=(await ops("boards",{user:B,title:`Search ${run}`})).board.id; await ops("members",{board,user:A});
const cookie=(await ops("sessions",{user:B})).cookie;
const mcp=async(name,args)=>(await (await fetch(`${BASE}/mcp?board=${board}`,{method:"POST",headers:{"content-type":"application/json",accept:"application/json, text/event-stream",authorization:`Bearer ${tokA}`},body:JSON.stringify({jsonrpc:"2.0",id:1,method:"tools/call",params:{name,arguments:args}})})).json()).result.content[0].text;
const web=(text,type="note")=>fetch(`${BASE}/api/boards/${board}/entries`,{method:"POST",headers:{"content-type":"application/json",cookie},body:JSON.stringify({type,text})});
const word=`zanzibar${run}`;
for(let i=0;i<30;i++){ if(i===4){await mcp("read",{});await mcp("post",{type:"question",text:`Which ${word} limit does the payments client use?`})} else if(i===12){await web(`The ${word} limit is 3 with exponential backoff`)} else if(i===20){await mcp("read",{});await mcp("post",{type:"task",title:"Raise limit",text:`Raise the ${word} limit to 5 for checkout`})} else await web(`filler message ${i} about nothing in particular`)}
let fails=0;const check=(ok,m)=>{console.log(`${ok?"✓":"✗"} ${m}`);if(!ok)fails++};
const b = await chromium.launch({ executablePath: process.env.PW_CHROME || undefined });
const ctx=await b.newContext({viewport:{width:1280,height:800}});const [k,...v]=cookie.split(";")[0].split("=");await ctx.addCookies([{name:k,value:v.join("="),url:BASE}]);
const p=await ctx.newPage();const errors=[];p.on("pageerror",e=>errors.push(e.message));
await p.goto(`${BASE}/b/${board}`);await p.waitForTimeout(600);
await p.locator("body").click({position:{x:5,y:300}}).catch(()=>{});
await p.keyboard.press("Control+f");await p.waitForTimeout(200);
check(await p.locator("#palette").isVisible(),"Ctrl+F opens the search palette");
check((await p.locator("#pal-chips").innerText()).replace(/✕|\n/g," ").includes("This board")&&(await p.locator("#pal-chips").innerText()).includes("Messages"),"…already filtered: This board · Messages");
await p.keyboard.type(word);await p.waitForTimeout(800);
const rows=()=>p.locator("#palette-list [data-n]").allInnerTexts();
let r=await rows();console.log("  results:",JSON.stringify(r.map(x=>x.replace(/\n/g," | "))));
check(r.length===3&&r.every(x=>x.toLowerCase().includes(word)),"three ranked message results");
check(await p.locator("#palette-list mark").count()>0,"matches highlighted");
await p.keyboard.press("Enter");await p.waitForTimeout(400);
check(!(await p.locator("#palette").isVisible())&&await p.locator("#thread .entry.hit").count()===1,"Enter jumps to the message and highlights it");
await p.keyboard.press("Control+k");await p.waitForTimeout(200);
const filt=await p.locator("#pal-filters").innerText();
check(["This board","Messages","Files","Boards","Actions","From…","Type…"].every(x=>filt.includes(x)),`Ctrl+K shows the filters up front (${filt.replace(/\n/g," · ")})`);
check((await rows()).length>0,"…and boards/actions before you type");
await p.locator('#pal-filters [data-popt="from"]').click();await p.waitForTimeout(200);
await p.keyboard.type(A.slice(0,4));await p.waitForTimeout(200);
r=await rows();check(r.some(x=>x.includes(`${A}'s agent`)),"From… lists people and agents");
await p.keyboard.press("ArrowDown");await p.keyboard.press("Enter");await p.waitForTimeout(200);
check((await p.locator("#pal-chips").innerText()).includes(`from ${A}'s agent`),"picking one makes a chip");
await p.keyboard.type(word);await p.waitForTimeout(800);
r=await rows();check(r.length===2&&r.every(x=>x.includes(`${A}'s agent`)),`narrowed to vedu's agent (${r.length})`);
await p.keyboard.press("Control+a");await p.keyboard.press("Backspace");await p.keyboard.press("Backspace");await p.waitForTimeout(300);
check(!(await p.locator("#pal-chips").innerText()).includes("from"),"Backspace on an empty box removes the last filter");
await p.keyboard.press("Escape");await p.waitForTimeout(200);
check(!(await p.locator("#palette").isVisible()),"Esc closes");
// from the boards page: messages across your boards
await p.goto(`${BASE}/`);await p.waitForTimeout(400);
await p.keyboard.press("Control+k");await p.keyboard.type(word);await p.waitForTimeout(1200);
r=await rows();console.log("  home results:",JSON.stringify(r.map(x=>x.replace(/\n/g," | "))));
check(r.some(x=>x.toLowerCase().includes(word)),"from the boards page, Ctrl+K finds messages across your boards");
await p.keyboard.press("Enter");await p.waitForTimeout(800);
check(p.url().includes(`/b/${board}#e`),`…and opens the board at that message (${p.url()})`);
await p.keyboard.press("Control+k");await p.waitForTimeout(200);await p.screenshot({path:`${SHOTS_DIR}/palette.png`});
check(errors.length===0,`no page errors ${errors.join(" | ")}`);
await b.close();console.log(fails?`${fails} FAILED`:"all search checks passed");
