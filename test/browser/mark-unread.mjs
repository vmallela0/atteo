import { chromium } from "playwright-core";
const BASE = process.env.BASE || "http://localhost:8787";
const ops = async (path, body) => (await (await fetch(`${BASE}/api/ops/${path}`, { method: "POST", headers: { "x-admin-key": process.env.ADMIN_KEY || "ci-admin-key", "content-type": "application/json" }, body: JSON.stringify(body) })).json());
const run = Date.now().toString(36).slice(-6), user = `mu${run}`;
await ops("users", { name: user, email: `${user}@example.com`, verified: "true" });
const board = (await ops("boards", { user, title: `Mark unread ${run}` })).board.id;
const cookie = (await ops("sessions", { user })).cookie;
const token = (await ops("tokens", { user })).token;
const browser = await chromium.launch({ executablePath: process.env.PW_CHROME || undefined });
const ctx = await browser.newContext();
const [name, ...rest] = cookie.split(";")[0].split("=");
await ctx.addCookies([{ name, value: rest.join("="), url: BASE }]);
const page = await ctx.newPage();
let fails = 0;
const check = (ok, message) => { console.log(`${ok ? "✓" : "✗"} ${message}`); if (!ok) fails++; };
const post = () => page.request.post(`${BASE}/api/boards/${board}/unread`);
const count = async () => (await (await page.request.get(`${BASE}/api/inbox/count`)).json()).unread;
// Already on /chats after a menu action that navigates there: let it finish and reload, rather than racing a second goto.
// Then wait for the badge itself (the list renders after its own fetch), not for the page load event.
const badge = async () => {
  await page.waitForLoadState("load");
  if (page.url() === `${BASE}/chats`) await page.reload(); else await page.goto(`${BASE}/chats`);
  const loc = page.locator(`.bcard[data-id="${board}"] .bc-unread`);
  const t = Date.now();
  for (;;) {
    const n = await loc.count();
    if (n === 1 || Date.now() - t > 6000) return n;
    await page.waitForTimeout(150);
  }
};
const entry = await (await page.request.post(`${BASE}/api/boards/${board}/entries`, { data: { text: `Follow up ${run}` } })).json();
const seq = entry.entry.seq;
await page.goto(`${BASE}/b/${board}`);
await page.request.post(`${BASE}/api/boards/${board}/seen`, { data: { seq } });
const before = await count();
const readsBefore = (await (await page.request.get(`${BASE}/api/boards/${board}/updates?after=0`)).json()).reads[user];
const agent = await fetch(`${BASE}/api/boards/${board}/unread`, { method: "POST", headers: { authorization: `Bearer ${token}` } });
check(agent.status === 403, "agent token is refused");
check((await count()) === before, "agent attempt leaves the person's unread count alone");
const response = await post(), result = await response.json();
check(response.ok && result.seq >= 1, "person can mark a board unread");
check((await count()) > before, "unread count comes back");
const readsAfter = (await (await page.request.get(`${BASE}/api/boards/${board}/updates?after=0`)).json()).reads[user];
check(readsAfter.person_seen === seq - 1, "person read receipt moves before the latest entry");
check(readsAfter.agent_seen === readsBefore.agent_seen, "agent read receipt stays unchanged");
check(await badge() === 1, "board list badge comes back");
await page.locator(`.side-board-row:has(a[href="/b/${board}"]) summary`).click();
await page.locator(`.side-board-row:has(a[href="/b/${board}"]) [data-mark-unread]`).click();
await page.waitForURL(`${BASE}/chats`);
check(await badge() === 1, "sidebar row menu keeps the board unread");
await page.goto(`${BASE}/b/${board}`);
await page.locator(".topbar .board-head-menu summary").click();
const menu = page.locator(`.topbar [data-mark-unread="${board}"]`);
check(await menu.count() === 1, "board's more actions include Mark as unread");
await menu.click();
await page.waitForURL(`${BASE}/chats`);
check(await badge() === 1, "board menu restores its badge");
await browser.close();
console.log(fails ? `${fails} FAILED` : "all mark-unread checks passed");
process.exit(fails ? 1 : 0);
