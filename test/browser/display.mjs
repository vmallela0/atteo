// Account → Display: text size, density and theme apply at once, survive a reload with no flash, and reach the board page.
import { SHOTS_DIR } from "./lib/shots.mjs";
import { chromium } from "playwright-core";
const BASE=process.env.BASE||"http://localhost:8787";
const ops = async (p, b) => (await fetch(`${BASE}/api/ops/${p}`, { method: "POST", headers: { "x-admin-key": "ci-admin-key", "content-type": "application/json" }, body: JSON.stringify(b) })).json();
const run=Date.now().toString(36).slice(-4), A=`dp${run}`;
await ops("users",{name:A,email:`${A}@example.com`,verified:"true"});
const tok=(await ops("tokens",{user:A})).token;
const board=(await ops("boards",{user:A,title:`Display ${run}`})).board.id;
const call=async(name,args)=>(await (await fetch(`${BASE}/mcp?board=${board}`,{method:"POST",headers:{"content-type":"application/json",authorization:`Bearer ${tok}`},body:JSON.stringify({jsonrpc:"2.0",id:1,method:"tools/call",params:{name,arguments:args}})})).json()).result.content[0].text;
await call("read",{});await call("post",{type:"note",text:"Hello there.",reply_to:0});await call("read",{});await call("post",{type:"note",text:"Second line.",reply_to:0});
const ck=(await ops("sessions",{user:A})).cookie;
let fails=0;const check=(ok,m)=>{console.log(`${ok?"✓":"✗"} ${m}`);if(!ok)fails++};
const b=await chromium.launch({executablePath: process.env.PW_CHROME || undefined});
const ctx=await b.newContext({viewport:{width:1280,height:800},colorScheme:"light"});const [k,...v]=ck.split(";")[0].split("=");await ctx.addCookies([{name:k,value:v.join("="),url:BASE}]);
const p=await ctx.newPage();const errors=[];p.on("pageerror",e=>errors.push(e.message));
const fs=()=>p.evaluate(()=>parseFloat(getComputedStyle(document.querySelector('.entry .body')).fontSize));
const pad=()=>p.evaluate(()=>parseFloat(getComputedStyle([...document.querySelectorAll('#thread>.entry')].pop()).paddingTop));
const bg=()=>p.evaluate(()=>getComputedStyle(document.body).backgroundColor);
await p.goto(`${BASE}/b/${board}`);await p.waitForSelector('.entry .body');
const [fs0,pad0,bg0]=[await fs(),await pad(),await bg()];
await p.goto(`${BASE}/me`);
check(await p.locator('#dp-form').isVisible(),"Account has a Display section");
check(await p.locator('#dp-text-m').isChecked()&&await p.locator('#dp-density-comfortable').isChecked()&&await p.locator('#dp-theme-system').isChecked(),"defaults: Medium, Comfortable, System");
await p.locator('label[for="dp-theme-dark"]').click();await p.waitForTimeout(150);
check(await bg()!==bg0&&await p.evaluate(()=>document.documentElement.dataset.theme)==="dark","Dark applies at once, though the system is light");
await p.locator('#dp-theme-light').focus();await p.keyboard.press("ArrowRight");await p.waitForTimeout(150);
check(await p.evaluate(()=>document.documentElement.dataset.theme)==="dark"||await p.locator('#dp-theme-dark').isChecked(),"the switches work from the keyboard");
await p.locator('label[for="dp-text-l"]').click();await p.locator('label[for="dp-density-compact"]').click();await p.waitForTimeout(300);
await p.goto(`${BASE}/b/${board}`);await p.waitForSelector('.entry .body');
check(await fs()>fs0,`Large text on the board: ${fs0}px → ${await fs()}px`);
check(await pad()<pad0,`Compact density: padding ${pad0}px → ${await pad()}px`);
check(await bg()!==bg0,"Dark theme on the board");
// No flash: the saved setting is on <html> before any script below the head runs.
const early=await p.evaluate(()=>performance.getEntriesByType("navigation").length&&document.documentElement.dataset.text);
check(early==="l","set on <html> from the head");
const saved=await (await p.request.get(`${BASE}/api/me/profile`)).json();
const srv=saved.profile&&saved.profile.display;
console.log("  server display:",JSON.stringify(srv??"(not stored by this server yet)"));
if(srv)check(srv.text==="l"&&srv.density==="compact"&&srv.theme==="dark","saved to the account");
await p.goto(`${BASE}/me`);await p.locator('label[for="dp-text-s"]').click();await p.locator('label[for="dp-theme-system"]').click();await p.locator('label[for="dp-density-comfortable"]').click();await p.waitForTimeout(300);
await p.goto(`${BASE}/b/${board}`);await p.waitForSelector('.entry .body');
check(await fs()<fs0&&await bg()===bg0&&await pad()===pad0,"Small + System + Comfortable go back cleanly");
await p.setViewportSize({width:360,height:740});await p.goto(`${BASE}/me`);
check(await p.evaluate(()=>document.documentElement.scrollWidth<=innerWidth),"360px: nothing overflows sideways");
await p.screenshot({path:`${SHOTS_DIR}/display-me-360.png`,fullPage:false,clip:{x:0,y:0,width:360,height:740}}).catch(()=>{});
check(!errors.length,`no page errors ${errors.join(" | ")}`);
await b.close();console.log(fails?`${fails} FAILED`:"all display checks passed");process.exit(fails?1:0);
