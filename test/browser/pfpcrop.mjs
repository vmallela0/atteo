// Picking a profile picture opens a crop step (move, zoom, rotate) before it's saved (vedu #1001).
import { SHOTS_DIR } from "./lib/shots.mjs";
import { chromium } from "playwright-core";
const BASE=process.env.BASE||"http://localhost:8787";
const ops = async (p, b) => (await fetch(`${BASE}/api/ops/${p}`, { method: "POST", headers: { "x-admin-key": "ci-admin-key", "content-type": "application/json" }, body: JSON.stringify(b) })).json();
const run=Date.now().toString(36).slice(-4), A=`pc${run}`;
await ops("users",{name:A,email:`${A}@example.com`,verified:"true"});const ck=(await ops("sessions",{user:A})).cookie;
let fails=0;const check=(ok,m)=>{console.log(`${ok?"✓":"✗"} ${m}`);if(!ok)fails++};
const b=await chromium.launch({executablePath: process.env.PW_CHROME || undefined});
const ctx=await b.newContext({viewport:{width:1100,height:860}});const [k,...v]=ck.split(";")[0].split("=");await ctx.addCookies([{name:k,value:v.join("="),url:BASE}]);
const p=await ctx.newPage();const errors=[];p.on("pageerror",e=>errors.push(e.message));await p.goto(`${BASE}/me`);
const png=await p.evaluate(async()=>{const c=document.createElement('canvas');c.width=600;c.height=300;const x=c.getContext('2d');x.fillStyle='#4ea1ff';x.fillRect(0,0,300,300);x.fillStyle='#16a34a';x.fillRect(300,0,300,300);return [...new Uint8Array(await (await new Promise(r=>c.toBlob(r,'image/png'))).arrayBuffer())]});
const file={name:"me.png",mimeType:"image/png",buffer:Buffer.from(png)};
await p.setInputFiles('.pfp[data-kind="person"] [data-pfp-file]',file);await p.waitForTimeout(400);
check(await p.locator('dialog.crop-dlg[open] canvas').isVisible(),"choosing a picture opens the crop step");
await p.screenshot({path:`${SHOTS_DIR}/pfpcrop.png`});
await p.locator('dialog.crop-dlg [data-no]').click();await p.waitForTimeout(300);
const before=(await (await p.request.get(`${BASE}/avatar/${A}`)).headers())["content-type"];
check(!(await p.locator('dialog.crop-dlg').count()),"Cancel closes it and saves nothing");
await p.setInputFiles('.pfp[data-kind="person"] [data-pfp-file]',file);await p.waitForTimeout(400);
const cv=p.locator('dialog.crop-dlg canvas');const bx=await cv.boundingBox();
await p.mouse.move(bx.x+140,bx.y+140);await p.mouse.down();await p.mouse.move(bx.x+40,bx.y+140,{steps:5});await p.mouse.up();
await p.locator('dialog.crop-dlg [data-z]').fill("2");await p.locator('dialog.crop-dlg [data-br]').fill("1.2");await p.locator('dialog.crop-dlg [data-rot]').click();
const resp=p.waitForResponse(r=>r.url().includes('/api/me/avatar')&&r.request().method()==='POST');
await p.locator('dialog.crop-dlg [data-ok]').click();const r=await resp;
check(r.status()===200,`Save uploads the cropped picture (${r.status()})`);
await p.waitForTimeout(800);
const ct=(await (await p.request.get(`${BASE}/avatar/${A}`)).headers())["content-type"];
check(/image\/(webp|jpeg)/.test(ct),`the new picture is served (${before} → ${ct})`);
check(!errors.length,`no page errors ${errors.join(" | ")}`);
await b.close();console.log(fails?`${fails} FAILED`:"all crop checks passed");process.exit(fails?1:0);
