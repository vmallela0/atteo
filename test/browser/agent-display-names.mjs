// Named agents in the web composer, message chips, author rows and inbox (vedu #5686).
import { chromium } from "playwright-core";

const BASE = process.env.BASE || "http://localhost:8787";
const ops = async (path, body) => (await fetch(`${BASE}/api/ops/${path}`, { method: "POST", headers: { "x-admin-key": process.env.ADMIN_KEY || "ci-admin-key", "content-type": "application/json" }, body: JSON.stringify(body) })).json();
const run = Date.now().toString(36).slice(-5), P = `ad${run}`, A = `ab${run}`, NAME = `Bender${run}`;
let fails = 0;
const check = (ok, text) => { console.log(`${ok ? "✓" : "✗"} ${text}`); if (!ok) fails++; };
for (const user of [P, A]) await ops("users", { name: user, email: `${user}@example.com`, verified: "true" });
const board = (await ops("boards", { user: P, title: `Agent display names ${run}` })).board.id;
await ops("members", { board, user: A });
const ckP = (await ops("sessions", { user: P })).cookie.split(";")[0];
const ckA = (await ops("sessions", { user: A })).cookie.split(";")[0];
const token = (await ops("tokens", { user: A })).token;
const profile = await fetch(`${BASE}/api/me/profile`, { method: "POST", headers: { cookie: ckA, "content-type": "application/json" }, body: JSON.stringify({ agent_name: NAME }) });
check(profile.ok, "the agent has a display name");
const api = (cookie, path, method = "GET", body) => fetch(`${BASE}${path}`, { method, headers: { cookie, "content-type": "application/json" }, body: body ? JSON.stringify(body) : undefined }).then((r) => r.json());

const browser = await chromium.launch({ executablePath: process.env.PW_CHROME || undefined });
const context = await browser.newContext({ viewport: { width: 1180, height: 800 } });
const [key, ...value] = ckP.split("=");
await context.addCookies([{ name: key, value: value.join("="), url: BASE }]);
const page = await context.newPage(), errors = [];
page.on("pageerror", (e) => errors.push(e.message));
await page.goto(`${BASE}/b/${board}`);
const composer = page.locator("#composer-text");
await composer.fill(`@${NAME.slice(0, 3)}`);
const choice = page.locator("#mention-menu li[role=option]", { hasText: NAME });
await choice.waitFor({ timeout: 5000 });
const label = await choice.innerText();
check(label.includes(NAME) && label.includes(`@${A}'s agent`), `picker shows the agent display name and handle (${label.replace(/\s+/g, " ")})`);
await choice.click();
check((await composer.inputValue()) === `@${A}'s agent `, "picking the agent inserts the canonical token");
await composer.fill(`@${A}'s agent check ${run}`);
await composer.press("Enter");
const sent = page.locator("#thread .entry", { hasText: `check ${run}` }).last();
await sent.waitFor({ timeout: 8000 });
const seq = Number(await sent.getAttribute("data-seq"));
const saved = await api(ckP, `/api/boards/${board}/entries?after=0`);
check(saved.entries?.find((e) => e.seq === seq)?.mentions?.some((m) => m.user === A && m.agent), "the server resolves the token to that agent");
const chip = sent.locator(`.mention.agent[data-user="${A}"]`);
check((await chip.innerText()) === `@${NAME} · ${A}'s agent`, "the sent message renders the name and owner");
await page.reload();
check((await page.locator(`#e${seq} .mention.agent[data-user="${A}"]`).innerText()) === `@${NAME} · ${A}'s agent`, "the name and owner survive reload");

await fetch(`${BASE}/api/boards/${board}/entries?after=0&ack=1`, { headers: { authorization: `Bearer ${token}` } });
const post = await fetch(`${BASE}/api/boards/${board}/entries`, { method: "POST", headers: { authorization: `Bearer ${token}`, "content-type": "application/json" }, body: JSON.stringify({ type: "note", text: `@${P} hello ${run}` }) });
check(post.ok, "the named agent posts a mention");
const author = page.locator("#thread .entry.by-agent", { hasText: `hello ${run}` }).last();
await author.waitFor({ timeout: 8000 });
check((await author.locator(".meta .who").innerText()) === `${NAME} · ${A}'s agent`, "the author row shows the name and owner");
const inbox = await api(ckP, "/api/inbox");
check(inbox.items?.some((i) => i.actor === A && i.actor_via === "agent" && i.actor_name === NAME), "the app notification carries the agent display name");
const count = await api(ckP, "/api/inbox/count");
check(count.latest?.actor_name === `${NAME} · ${A}'s agent`, "the browser notification title carries the owner");
await page.goto(`${BASE}/inbox`);
check(await page.locator(".inbox-item b", { hasText: `${NAME} · ${A}'s agent` }).count() > 0, "the inbox shows the name and owner");
await page.goto(`${BASE}/b/${board}`);
await composer.fill(`@${NAME} please review`);
check(await page.locator("#mention-menu").isHidden(), "typing prose after a complete name closes the @ menu");
check((await fetch(`${BASE}/api/me/profile`, { method: "POST", headers: { cookie: ckP, "content-type": "application/json" }, body: JSON.stringify({ agent_name: NAME }) })).ok, "another member may use the same agent name");
const tokenP = (await ops("tokens", { user: P })).token;
await fetch(`${BASE}/api/boards/${board}/entries?after=0&ack=1`, { headers: { authorization: `Bearer ${tokenP}` } });
const second = await fetch(`${BASE}/api/boards/${board}/entries`, { method: "POST", headers: { authorization: `Bearer ${tokenP}`, "content-type": "application/json" }, body: JSON.stringify({ type: "note", text: `second named agent ${run}` }) });
check(second.ok, "the second named agent posts");
await page.reload();
check((await page.locator("#board-info").innerText()).includes("More than one agent here is named"), "Board info flags duplicate agent names");
check((await page.locator("#thread .entry.by-agent .who").allInnerTexts()).filter((s) => s === `${NAME} · ${A}'s agent`).length > 0, "the first duplicate keeps its owner");
check((await page.locator("#thread .entry.by-agent .who").allInnerTexts()).filter((s) => s === `${NAME} · ${P}'s agent`).length > 0, "the second duplicate keeps its owner");
check(!errors.length, `no page errors ${errors.join(" | ")}`);
await browser.close();
console.log(fails ? `${fails} FAILED` : "agent display names: all passed");
process.exit(fails ? 1 : 0);
