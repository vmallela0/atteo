// Search on an end-to-end encrypted board runs on the device. The CLI and the web page share src/localSearch.ts's
// algorithm (test/e2eweb.test.mjs); the iPhone app has a Swift port (ios/AgentSoup/Sources/LocalSearch.swift), checked
// against what this module answers for the cases below: ios/AtteoTests/LocalSearchFixtures.swift, regenerated with
// UPDATE_LOCAL_SEARCH=1 npx vitest run test/localSearch.test.ts.
import { describe, expect, it } from "vitest";
import { type LocalEntry, searchEntries } from "../src/localSearch";

const { readFileSync, writeFileSync } = (await import("node:" + "fs")) as { readFileSync: (p: string, enc: string) => string; writeFileSync: (p: string, d: string) => void };
const env = (globalThis as { process?: { env: Record<string, string | undefined> } }).process?.env ?? {};

const long = "We looked at every option for the rollout. ".repeat(4) + "The removal of the old flag happens after the canary is green, and only then. " + "More words follow here so the snippet is cut at the end too. ".repeat(4);
const ENTRIES: LocalEntry[] = [
  { seq: 1, ts: 1000, author: "ann", via: "person", type: "note", text: "hello web, first message" },
  { seq: 2, ts: 2000, author: "bob", via: "agent", type: "note", text: "Removal plan: remove the flag, then deploy" },
  { seq: 3, ts: 3000, author: "ann", via: "person", type: "question", text: "Is the removal safe?\nAsk @bob first." },
  { seq: 4, ts: 4000, author: "bob", via: "person", type: "decision", text: long },
  { seq: 5, ts: 5000, author: "cy", via: "agent", type: "note", text: "prefix_removal isn't a word start; unremovable neither" },
  { seq: 6, ts: 6000, author: "ann", via: "person", type: "note", text: "Café déjà vu: naïve résumé, Ünïcode 東京 tokyo" },
  { seq: 7, ts: 7000, author: "dee", via: "person", type: "note", text: "emoji 🎉 party then removal 🚀 launch" },
  { seq: 8, ts: 8000, author: "bob", via: "agent", type: "task", text: "Deploy   the\n\n  removal\tafter review" },
  { seq: 9, ts: 9000, author: "ann", via: "person", type: "note", text: "İstanbul trip: İ is longer when lowercased" },
  { seq: 10, ts: 10000, author: "eve", via: "person", type: "note", text: "x1 and 2x and _under score and v2.0 release" },
];

const CASES: { q: string; from?: string; agent?: boolean; type?: string }[] = [
  { q: "removal" },
  { q: "REMOVAL" },
  { q: "remov" },
  { q: "removal deploy" },
  { q: "removal flag" },
  { q: "moval" },
  { q: "hello web" },
  { q: "café" },
  { q: "déjà résumé" },
  { q: "東京" },
  { q: "tokyo" },
  { q: "launch" },
  { q: "İstanbul" },
  { q: "longer" },
  { q: "under" },
  { q: "_under" },
  { q: "2x" },
  { q: "release v2" },
  { q: "" },
  { q: "   " },
  { q: "nothing-here" },
  { q: "removal", from: "bob" },
  { q: "removal", agent: true },
  { q: "removal", agent: false },
  { q: "removal", type: "question" },
  { q: "the", from: "bob", agent: false },
  { q: "canary" },
];

function fixture(): string {
  const cases = CASES.map((c) => ({ ...c, hits: searchEntries(ENTRIES, c.q, c).map((h) => ({ seq: h.seq, snippet: h.snippet })) }));
  const b64 = btoa(Array.from(new TextEncoder().encode(JSON.stringify({ entries: ENTRIES, cases })), (b) => String.fromCharCode(b)).join(""));
  return `// Generated by test/localSearch.test.ts from src/localSearch.ts (searchEntries): don't edit by hand.
// ${cases.length} queries over ${ENTRIES.length} messages: {entries, cases: [{q, from?, agent?, type?, hits: [{seq, snippet}]}]} as base64 JSON.

enum LocalSearchFixtures {
    static let json = "${b64}"
}
`;
}

describe("on-device search on the iPhone", () => {
  it("has cases that find something and cases that don't", () => {
    const n = CASES.map((c) => searchEntries(ENTRIES, c.q, c).length);
    expect(n.filter((x) => x > 0).length).toBeGreaterThan(15);
    expect(n.filter((x) => x === 0).length).toBeGreaterThan(2);
  });

  it("the app's fixtures are this module's answers", () => {
    const path = "ios/AtteoTests/LocalSearchFixtures.swift";
    if (env.UPDATE_LOCAL_SEARCH) writeFileSync(path, fixture());
    expect(readFileSync(path, "utf8")).toBe(fixture());
  });
});
